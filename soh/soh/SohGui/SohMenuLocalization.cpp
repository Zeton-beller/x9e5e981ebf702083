std::string TranslateSidebar(const std::string& sidebar) {
    auto it = sSidebarMap.find(sidebar);
    if (it != sSidebarMap.end()) {
        return it->second;
    }
    return sidebar;
}

std::string TranslateHeader(const std::string& header) {
    auto it = sHeaderMap.find(header);
    if (it != sHeaderMap.end()) {
        return it->second;
    }
    return header;
}

const char* TranslateComboOption(const char* option) {
    if (!option) return nullptr;
    auto it = sComboOptionMap.find(option);
    if (it != sComboOptionMap.end()) {
        return it->second.c_str();
    }
    return option;
}

void ApplySohMenuLocalization(std::unordered_map<std::string, MainMenuEntry>& menuEntries) {
    for (auto& [menuKey, menuEntry] : menuEntries) {
        auto itHeader = sHeaderMap.find(menuEntry.label);
        if (itHeader != sHeaderMap.end()) {
            menuEntry.label = itHeader->second;
        }

        for (auto& [sidebarKey, sidebar] : menuEntry.sidebars) {
            for (auto& col : sidebar.columnWidgets) {
                for (auto& widget : col) {
                    auto itName = sWidgetNameMap.find(widget.name);
                    if (itName != sWidgetNameMap.end()) {
                        widget.name = itName->second;
                    }

                    if (widget.options) {
                        if (!widget.options->tooltip.empty()) {
                            auto itTooltip = sTooltipMap.find(widget.options->tooltip);
                            if (itTooltip != sTooltipMap.end()) {
                                widget.options->tooltip = itTooltip->second;
                            }
                        }

                        if (!widget.options->disabledTooltip.empty()) {
                            auto itDisabledTooltip = sTooltipMap.find(widget.options->disabledTooltip);
                            if (itDisabledTooltip != sTooltipMap.end()) {
                                widget.options->disabledTooltip = itDisabledTooltip->second;
                            }
                        }
                    }

                    if (widget.type == WIDGET_COMBOBOX || widget.type == WIDGET_CVAR_COMBOBOX) {
                        auto comboOpt = std::static_pointer_cast<UIWidgets::ComboboxOptions>(widget.options);
                        if (comboOpt) {
                            for (auto& [val, text] : comboOpt->comboMap) {
                                if (text) {
                                    auto itOpt = sComboOptionMap.find(text);
                                    if (itOpt != sComboOptionMap.end()) {
                                        text = itOpt->second.c_str();
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

